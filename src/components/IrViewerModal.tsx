import React, { useState } from 'react';
import {
  X,
  Copy,
  Check,
  Sparkles,
  FileCode,
  ArrowRightLeft,
  Search,
  ExternalLink
} from 'lucide-react';

interface IrViewerModalProps {
  isOpen: boolean;
  onClose: () => void;
  traditionalIR: string;
  llmOptimizedIR: string;
  passesApplied: string[];
}

export const IrViewerModal: React.FC<IrViewerModalProps> = ({
  isOpen,
  onClose,
  traditionalIR,
  llmOptimizedIR,
  passesApplied,
}) => {
  const [activeTab, setActiveTab] = useState<'traditional' | 'llm' | 'diff'>('diff');
  const [copied, setCopied] = useState(false);
  const [searchTerm, setSearchTerm] = useState('');
  const [aiDiffExplanation, setAiDiffExplanation] = useState<string | null>(null);
  const [isAnalyzing, setIsAnalyzing] = useState(false);

  if (!isOpen) return null;

  const handleCopy = (text: string) => {
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleAnalyzeDiffWithGemini = async () => {
    setIsAnalyzing(true);
    try {
      const res = await fetch('/api/analyze-ir', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          traditionalIR,
          llmOptimizedIR,
          passes: passesApplied,
        }),
      });
      const data = await res.json();
      setAiDiffExplanation(data.diffExplanation || 'Analysis complete.');
    } catch {
      setAiDiffExplanation('Failed to analyze IR difference with Gemini.');
    } finally {
      setIsAnalyzing(false);
    }
  };

  const filterLines = (code: string) => {
    if (!searchTerm) return code;
    return code
      .split('\n')
      .filter((line) => line.toLowerCase().includes(searchTerm.toLowerCase()))
      .join('\n');
  };

  const tradLines = traditionalIR ? traditionalIR.split('\n').length : 0;
  const llmLines = llmOptimizedIR ? llmOptimizedIR.split('\n').length : 0;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-md transition-opacity">
      <div className="relative w-full max-w-5xl h-[85vh] rounded-3xl apple-glass shadow-2xl flex flex-col overflow-hidden text-xs">
        {/* Modal Top Header */}
        <div className="px-6 py-4 border-b border-black/[0.06] dark:border-white/[0.08] flex items-center justify-between">
          <div className="flex items-center space-x-3">
            <div className="w-8 h-8 rounded-xl apple-glass-pill flex items-center justify-center text-zinc-900 dark:text-white">
              <FileCode className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-sm font-semibold text-zinc-900 dark:text-white tracking-tight">
                LLVM Intermediate Representation (IR) Inspector
              </h3>
              <p className="text-[11px] text-zinc-500 dark:text-zinc-400">
                Inspect and compare LLVM SSA assembly generated by Traditional vs LLM-Assisted Pipelines
              </p>
            </div>
          </div>

          <div className="flex items-center space-x-2">
            {/* AI Diff Button */}
            <button
              onClick={handleAnalyzeDiffWithGemini}
              disabled={isAnalyzing}
              className="flex items-center space-x-1.5 px-3 py-1.5 rounded-xl bg-black dark:bg-white text-white dark:text-black font-semibold transition-opacity cursor-pointer shadow-sm hover:opacity-90"
            >
              <Sparkles className="w-3.5 h-3.5" />
              <span>{isAnalyzing ? 'Analyzing IR...' : 'Gemini IR Diff Analysis'}</span>
            </button>

            {/* Close Button */}
            <button
              onClick={onClose}
              className="w-7 h-7 rounded-full apple-glass-pill flex items-center justify-center text-zinc-500 hover:text-zinc-900 dark:hover:text-white cursor-pointer transition-colors"
            >
              <X className="w-4 h-4" />
            </button>
          </div>
        </div>

        {/* AI Diff Summary if requested */}
        {aiDiffExplanation && (
          <div className="px-6 py-3 bg-black/[0.02] dark:bg-white/[0.03] border-b border-black/[0.06] dark:border-white/[0.08] text-xs text-zinc-800 dark:text-zinc-200 flex items-start space-x-2.5">
            <Sparkles className="w-4 h-4 text-zinc-900 dark:text-white shrink-0 mt-0.5" />
            <div className="flex-1">
              <span className="font-semibold text-zinc-900 dark:text-white uppercase tracking-wider text-[10px] block">
                Gemini IR Analysis:
              </span>
              <p className="mt-0.5 leading-relaxed">{aiDiffExplanation}</p>
            </div>
            <button
              onClick={() => setAiDiffExplanation(null)}
              className="text-zinc-500 hover:text-zinc-900 dark:hover:text-white cursor-pointer"
            >
              <X className="w-3.5 h-3.5" />
            </button>
          </div>
        )}

        {/* Sub-toolbar: Tab selection & Search */}
        <div className="px-6 py-2.5 border-b border-black/[0.04] dark:border-white/[0.06] flex items-center justify-between gap-4">
          {/* Segmented Tab */}
          <div className="flex items-center p-0.5 rounded-xl apple-glass-pill text-xs">
            <button
              onClick={() => setActiveTab('diff')}
              className={`px-3 py-1 rounded-lg font-medium transition-all cursor-pointer ${
                activeTab === 'diff'
                  ? 'bg-black text-white dark:bg-white dark:text-black shadow-sm'
                  : 'text-zinc-500 hover:text-zinc-900 dark:hover:text-white'
              }`}
            >
              Side-by-Side Comparison
            </button>
            <button
              onClick={() => setActiveTab('llm')}
              className={`px-3 py-1 rounded-lg font-medium transition-all cursor-pointer ${
                activeTab === 'llm'
                  ? 'bg-black text-white dark:bg-white dark:text-black shadow-sm'
                  : 'text-zinc-500 hover:text-zinc-900 dark:hover:text-white'
              }`}
            >
              LLM-Optimized IR ({llmLines} lines)
            </button>
            <button
              onClick={() => setActiveTab('traditional')}
              className={`px-3 py-1 rounded-lg font-medium transition-all cursor-pointer ${
                activeTab === 'traditional'
                  ? 'bg-black text-white dark:bg-white dark:text-black shadow-sm'
                  : 'text-zinc-500 hover:text-zinc-900 dark:hover:text-white'
              }`}
            >
              Baseline IR ({tradLines} lines)
            </button>
          </div>

          {/* Search Box */}
          <div className="relative w-64">
            <Search className="w-3.5 h-3.5 text-zinc-400 absolute left-2.5 top-1/2 -translate-y-1/2" />
            <input
              type="text"
              value={searchTerm}
              onChange={(e) => setSearchTerm(e.target.value)}
              placeholder="Filter IR instructions..."
              className="w-full pl-8 pr-3 py-1.5 rounded-xl apple-glass-pill text-zinc-900 dark:text-white placeholder:text-zinc-400 text-xs focus:outline-none"
            />
          </div>
        </div>

        {/* IR Viewer Code Surface */}
        <div className="flex-1 overflow-hidden p-4">
          {activeTab === 'diff' ? (
            <div className="grid grid-cols-2 gap-4 h-full">
              {/* Baseline IR Column */}
              <div className="flex flex-col h-full rounded-2xl apple-glass-pill overflow-hidden">
                <div className="px-3 py-2 border-b border-black/[0.04] dark:border-white/[0.06] flex items-center justify-between text-[11px] font-mono text-zinc-500 dark:text-zinc-400">
                  <span>Baseline IR (Clang -O2) • {tradLines} lines</span>
                  <button
                    onClick={() => handleCopy(traditionalIR)}
                    className="hover:text-zinc-900 dark:hover:text-white cursor-pointer"
                  >
                    <Copy className="w-3 h-3" />
                  </button>
                </div>
                <pre className="flex-1 p-3 font-mono text-[11px] leading-5 overflow-auto text-zinc-800 dark:text-zinc-200 whitespace-pre">
                  {filterLines(traditionalIR) || '; No IR code available'}
                </pre>
              </div>

              {/* LLM-Assisted IR Column */}
              <div className="flex flex-col h-full rounded-2xl apple-glass-pill overflow-hidden">
                <div className="px-3 py-2 border-b border-black/[0.04] dark:border-white/[0.06] flex items-center justify-between text-[11px] font-mono text-zinc-900 dark:text-white font-semibold">
                  <span>LLM Optimized IR ({passesApplied.join(', ')}) • {llmLines} lines</span>
                  <button
                    onClick={() => handleCopy(llmOptimizedIR)}
                    className="hover:text-zinc-900 dark:hover:text-white cursor-pointer"
                  >
                    <Copy className="w-3 h-3" />
                  </button>
                </div>
                <pre className="flex-1 p-3 font-mono text-[11px] leading-5 overflow-auto text-zinc-800 dark:text-zinc-200 whitespace-pre">
                  {filterLines(llmOptimizedIR) || '; No IR code available'}
                </pre>
              </div>
            </div>
          ) : activeTab === 'llm' ? (
            <div className="h-full rounded-2xl apple-glass-pill p-4 font-mono text-[11.5px] leading-5 overflow-auto text-zinc-800 dark:text-zinc-200 whitespace-pre">
              {filterLines(llmOptimizedIR)}
            </div>
          ) : (
            <div className="h-full rounded-2xl apple-glass-pill p-4 font-mono text-[11.5px] leading-5 overflow-auto text-zinc-800 dark:text-zinc-200 whitespace-pre">
              {filterLines(traditionalIR)}
            </div>
          )}
        </div>

        {/* Modal Footer */}
        <div className="px-6 py-2.5 border-t border-black/[0.06] dark:border-white/[0.08] flex items-center justify-between text-[11px] font-mono text-zinc-500 dark:text-zinc-400">
          <span>LLVM IR Target: x86_64-pc-linux-gnu</span>
          <span>Delta: {Math.abs(tradLines - llmLines)} lines {llmLines < tradLines ? 'smaller' : 'expanded'}</span>
        </div>
      </div>
    </div>
  );
};
